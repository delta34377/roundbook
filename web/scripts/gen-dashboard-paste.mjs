// gen-dashboard-paste.mjs — regenerates DASHBOARD_PASTE.ts from the three
// source files (arccos.ts + derive.ts + index.ts), which stay the source of
// truth. The paste is the same code as ONE file: section banners between the
// parts, `export ` keywords dropped, the createClient import hoisted to the
// top, and the relative imports removed. Run after touching any of the three:
//   node web/scripts/gen-dashboard-paste.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..',
  'supabase', 'functions', 'arccos-sync');
const read = (f) => fs.readFileSync(path.join(dir, f), 'utf8');
const noExports = (s) => s.replace(/^export /gm, '');
const banner = (name) =>
  `// ===================== ${name} =====================\n`;

const arccos = noExports(read('arccos.ts'));
const derive = noExports(read('derive.ts'));
const index = read('index.ts')
  .replace(/^import { createClient } from 'jsr:@supabase\/supabase-js@2';\n/m, '')
  .replace(/^import { deriveDashData } from '\.\/derive\.ts';\n/m, '')
  .replace(/^import { ArccosError, [^\n]*} from '\.\/arccos\.ts';\n/m, '');

// index.ts keeps its leading comment block; the imports sat below it. Splice
// the function body (everything) after the two other sections.
const out =
  `// DASHBOARD_PASTE.ts — the arccos-sync function as ONE file, for deploying\n` +
  `// from the Supabase dashboard's function editor (no CLI needed). Generated by\n` +
  `// concatenating arccos.ts + derive.ts + index.ts verbatim (imports/exports\n` +
  `// between them removed). Those three files remain the source of truth: if\n` +
  `// they change, regenerate this file (node web/scripts/gen-dashboard-paste.mjs)\n` +
  `// and redeploy the paste.\n` +
  `import { createClient } from 'jsr:@supabase/supabase-js@2';\n\n` +
  banner('arccos.ts') + arccos + '\n' +
  banner('derive.ts') + derive + '\n' +
  banner('index.ts') + index;

fs.writeFileSync(path.join(dir, 'DASHBOARD_PASTE.ts'), out);
console.log('wrote DASHBOARD_PASTE.ts', out.length, 'chars');
